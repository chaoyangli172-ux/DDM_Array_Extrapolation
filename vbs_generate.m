%% generate_EEP_export_vbs.m
% ------------------------------------------------------------------------
% Purpose:
%   Automatically generates a generic VBScript based on the user-defined
%   HFSS project name, design name, number of ports, report name, and
%   output folder.
%
%   The generated VBS script sequentially excites each port individually
%   (1 W, 0 deg) while setting all other ports to zero excitation, and
%   exports the Embedded Element Pattern (EEP) of each port as
%
%       rE Plot 1.csv
%       rE Plot 2.csv
%       ...
%       rE Plot N.csv
%
% Design Notes:
%   Instead of letting MATLAB generate N independent EditSources code
%   blocks using a for-loop, the generated VBS performs the iteration
%   internally using a For loop and dynamically allocated arrays (ReDim).
%
%   As a result, the generated VBS script supports any number of ports
%   without relying on regular-expression replacement or regenerating
%   dozens of static Array(...) statements whenever the array size changes.
%
% Usage:
%   Modify the variables in the "User Configuration" section below,
%   including:
%
%       projectName
%       designName
%       numPorts
%       reportName
%       outputFolder
%       vbsSavePath
%
%   Then run this MATLAB script to generate the VBS file.
%
%   On the computer where HFSS is installed, open the corresponding
%   project manually and execute the generated VBS using
%
%       cscript.exe
%
%   The script connects to the currently running HFSS session via
%   CreateObject("Ansoft.ElectronicsDesktop").
% ------------------------------------------------------------------------

clear; clc;

%% ===================== User Configuration =====================
projectName  = 'Ku_phased_array';                            % HFSS project name
designName   = 'HFSSDesign1';                                   % HFSS design name
numPorts     = 32;                                                % total number of array ports
reportName   = 'rE Plot 1';                                       % name of the far-field report in the Report Tree (normally does not need to be modified)
outputFolder = 'C:/Users/PC/Desktop/matlab/EEP/';                 % Output folder for exported CSV files (Make sure the path ends with '/' or '\')
vbsSavePath  = 'C:/Users/PC/Desktop/matlab/EEP/EEP_export_auto.vbs';  % Output path of the generated VBS script

% Ensure that outputfolder ends with a path seperator to avoid filename concatenation errors.
if ~isempty(outputFolder) && ~any(outputFolder(end) == '/\')
    outputFolder = [outputFolder, '/'];
end

%% ===================== Validation =====================
if ~isnumeric(numPorts) || numPorts < 1 || mod(numPorts,1) ~= 0
    error('The number of array ports must be integer');
end

%% ===================== VBS Template =====================
vbsTemplate = [ ...
"' ----------------------------------------------" + newline + ...
"' Auto-generated by MATLAB - EEP batch export script" + newline + ...
"' Export EEP (Embedded Element Pattern) of each port" + newline + ...
"' ----------------------------------------------" + newline + ...
"Dim oAnsoftApp, oDesktop, oProject, oDesign, oModule" + newline + ...
"Dim NumPorts, activePort, i" + newline + ...
"Dim sourcesArr(), outputFolder" + newline + ...
"Dim fso, logFile" + newline + ...
"" + newline + ...
"NumPorts = %d" + newline + ...
"outputFolder = ""%s""" + newline + ...
"" + newline + ...
"' Log export progress to a text file instead of using Wscript. Echo（Message boxes require user interaction " + newline + ...
"' and become inconvenient when exporting a large number of ports）" + newline + ...
"Set fso = CreateObject(""Scripting.FileSystemObject"")" + newline + ...
"Set logFile = fso.OpenTextFile(outputFolder & ""export_log.txt"", 2, True)" + newline + ...
"" + newline + ...
"Set oAnsoftApp = CreateObject(""Ansoft.ElectronicsDesktop"")" + newline + ...
"Set oDesktop = oAnsoftApp.GetAppDesktop()" + newline + ...
"oDesktop.RestoreWindow" + newline + ...
"Set oProject = oDesktop.SetActiveProject(""%s"")" + newline + ...
"Set oDesign = oProject.SetActiveDesign(""%s"")" + newline + ...
"" + newline + ...
"For activePort = 1 To NumPorts" + newline + ...
"    Set oModule = oDesign.GetModule(""Solutions"")" + newline + ...
"    ReDim sourcesArr(NumPorts)" + newline + ...
"    sourcesArr(0) = Array(""IncludePortPostProcessing:="", false, ""SpecifySystemPower:="", false)" + newline + ...
"    For i = 1 To NumPorts" + newline + ...
"        If i = activePort Then" + newline + ...
"            sourcesArr(i) = Array(""Name:="", CStr(i) & "":1"", ""Magnitude:="", ""1W"", ""Phase:="", ""0deg"")" + newline + ...
"        Else" + newline + ...
"            sourcesArr(i) = Array(""Name:="", CStr(i) & "":1"", ""Magnitude:="", ""0W"", ""Phase:="", ""0deg"")" + newline + ...
"        End If" + newline + ...
"    Next" + newline + ...
"    oModule.EditSources(sourcesArr)" + newline + ...
"" + newline + ...
"    Set oModule = oDesign.GetModule(""ReportSetup"")" + newline + ...
"    oModule.ExportToFile ""%s"", outputFolder & ""rE Plot "" & CStr(activePort) & "".csv"", false" + newline + ...
"" + newline + ...
"    logFile.WriteLine ""Port "" & activePort & "" / "" & NumPorts & "" exported.""" + newline + ...
"Next" + newline + ...
"" + newline + ...
"logFile.WriteLine ""All "" & NumPorts & "" ports exported successfully.""" + newline + ...
"logFile.Close" ...
];

vbsContent = sprintf(vbsTemplate, numPorts, outputFolder, projectName, designName, reportName);

%% ===================== Write VBS file =====================
fid = fopen(vbsSavePath, 'w');
if fid == -1
    error('Unable to create file: %s，Please check whether the destination path exsits and is writable', vbsSavePath);
end
fwrite(fid, vbsContent, 'char');
fclose(fid);

fprintf('VBS script generated successfully: %s\n', vbsSavePath);
fprintf('The script will export %d Embedded Element Pattern (EEP) files: "rE Plot 1.csv" ~ "rE Plot %d.csv"\n', numPorts, numPorts);
fprintf('Output directory: %s\n', outputFolder);
fprintf('Progress is recorded in: %sexport_log.txt\n', outputFolder);
fprintf('\n Execution command Open the corresponding HFSS project before running the script):\n');
fprintf('    cscript.exe "%s"\n', vbsSavePath);
